const registry: Record<Locale, HubCopy> = { en, fr, ar, ber: fr };

export type { HubCopy };

export function useHubCopy(): HubCopy {
  const { locale } = useLocale();
  return registry[locale] ?? en;
}

/** Protocol text in the reader's language, falling back to the stored English. */
export function protocolText(
  c: HubCopy,
  p: {
    slug: string;
    title: string;
    description: string;
    steps: Array<{ label: string }>;
  },
): ProtocolCopy {
  const tr = c.protocolsI18n?.[p.slug];
  return (
    tr ?? {
      title: p.title,
      description: p.description,
      steps: p.steps.map((s) => s.label),
    }
  );
}

export function fmtDate(
  c: HubCopy,
  d: string | Date,
  opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short" },
) {
  return new Date(d).toLocaleDateString(c.dateLocale, opts);
}
